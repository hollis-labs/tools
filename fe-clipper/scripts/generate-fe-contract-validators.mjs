import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contractRoot = path.join(root, "vendor/fragments-engine-browser-contract-v1");
const schemaRoot = path.join(contractRoot, "schema");
const outputPath = path.join(root, "src/generated/fe-contract-validators.js");
const declarationPath = path.join(root, "src/generated/fe-contract-validators.d.ts");
const checkOnly = process.argv.includes("--check");

const manifest = JSON.parse(
  readFileSync(path.join(contractRoot, "contract-manifest.json"), "utf8"),
);
const schemas = readdirSync(schemaRoot)
  .filter((name) => name.endsWith(".json"))
  .sort()
  .map((name) => ({
    relativePath: `schema/${name}`,
    schema: JSON.parse(readFileSync(path.join(schemaRoot, name), "utf8")),
  }));
const schemasByRelativePath = new Map(schemas.map(({ relativePath, schema }) => [relativePath, schema]));

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  validateFormats: true,
  code: { source: true, esm: true, lines: true },
});
addFormats(ajv);

for (const { schema } of schemas) {
  if (typeof schema.$id !== "string" || !schema.$id) {
    throw new Error("Every pinned FE schema must declare a non-empty $id.");
  }
  ajv.addSchema(schema, schema.$id);
}

const exportsByName = {};
const validatorReferences = [];
for (const [name, relativePath] of Object.entries(manifest.schemas)) {
  const schema = schemasByRelativePath.get(relativePath);
  if (!schema) {
    throw new Error(`Pinned FE contract root ${name} points to missing ${relativePath}.`);
  }
  const exportName = `root_${name.replaceAll(/[^A-Za-z0-9_$]/g, "_")}`;
  exportsByName[exportName] = schema.$id;
  validatorReferences.push([schema.$id, exportName]);
}

const mediaSchema = schemasByRelativePath.get("schema/media.schema.json");
if (!mediaSchema) throw new Error("Pinned FE media schema is missing.");
for (const [name, definition] of [
  ["capture_media_item", "CaptureMediaItem"],
  ["capture_asset_variant", "CaptureAssetVariant"],
  ["asset_instruction", "AssetInstruction"],
  ["asset_outcome", "AssetOutcome"],
]) {
  const reference = `${mediaSchema.$id}#/$defs/${definition}`;
  const exportName = `definition_${name}`;
  exportsByName[exportName] = reference;
  validatorReferences.push([reference, exportName]);
}

for (const reference of Object.values(exportsByName)) {
  if (!ajv.getSchema(reference)) {
    throw new Error(`Pinned FE contract validator is unavailable for ${reference}.`);
  }
}

function convertStandaloneRequiresToEsm(source) {
  let converted = source.replace(
    /const ([A-Za-z_$][A-Za-z0-9_$]*) = require\("([^"]+)"\)\.default;/gu,
    (_match, identifier, specifier) =>
      `import * as ${identifier}Module from "${specifier}.js";\n` +
      `const ${identifier} = ${identifier}Module.default?.default ?? ${identifier}Module.default;`,
  );
  if (converted.includes('require("ajv-formats/dist/formats").fullFormats')) {
    converted = `import * as formatsModule from "ajv-formats/dist/formats.js";\n${converted.replaceAll(
      'require("ajv-formats/dist/formats").fullFormats',
      "formatsModule.fullFormats",
    )}`;
  }
  const remainingRequires = converted.match(/\brequire\s*\(/gu);
  if (remainingRequires) {
    throw new Error("Ajv standalone output contains an unconverted CommonJS require().");
  }
  return converted;
}

const generatedSource = `${[
  "// Generated by scripts/generate-fe-contract-validators.mjs.",
  "// Do not edit by hand. These static functions keep MV3 runtime code free of eval/new Function.",
  convertStandaloneRequiresToEsm(standaloneCode(ajv, exportsByName)),
  "export const validatorsBySchemaReference = Object.freeze({",
  ...validatorReferences.map(
    ([reference, exportName]) => `  ${JSON.stringify(reference)}: ${exportName},`,
  ),
  "});",
  "",
].join("\n")}`;

const generatedDeclaration = `// Generated by scripts/generate-fe-contract-validators.mjs.\n// Do not edit by hand.\nimport type { ValidateFunction } from "ajv";\n\nexport const validatorsBySchemaReference: Readonly<Record<string, ValidateFunction>>;\n`;

function updateOrCheck(filePath, expected) {
  const existing = existsSync(filePath) ? readFileSync(filePath, "utf8") : undefined;
  if (existing === expected) return;
  if (checkOnly) {
    throw new Error(
      `${path.relative(root, filePath)} is stale. Run npm run contracts:validators.`,
    );
  }
  writeFileSync(filePath, expected);
}

updateOrCheck(outputPath, generatedSource);
updateOrCheck(declarationPath, generatedDeclaration);

if (checkOnly) {
  const generatedModule = await import(
    `${pathToFileURL(outputPath).href}?contract-check=${Date.now()}`
  );
  for (const [reference] of validatorReferences) {
    if (typeof generatedModule.validatorsBySchemaReference?.[reference] !== "function") {
      throw new Error(`Generated ESM module is missing validator ${reference}.`);
    }
  }
}

console.log(
  checkOnly
    ? "Generated FE standalone validators match the pinned schemas byte-for-byte."
    : "Generated FE standalone validators from the pinned schemas.",
);
